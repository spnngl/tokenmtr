//! `apps/desktop/src/shared/bindings.ts`: the command, event and error names the UI checks itself
//! against, and the brand strings (`tokenmtr-brand`) it displays.
//!
//! The wire shapes are validated in the UI by Zod (the schemas mirror the `tokenmtr-query` serde
//! output), so only the names are generated: a renamed or removed command makes the UI test that
//! compares `TauriDataSource` with `COMMANDS` fail instead of failing at runtime.
//! `just bindings` rewrites the file; CI fails when the committed copy is stale.

use std::fmt::Write as _;

use tokenmtr_core::brand;

use crate::commands::NAMES;
use crate::error::ErrorKind;
use crate::push::{ALERT_FIRED, DAEMON_STATE, NAVIGATE, STORE_CHANGED};
use crate::windows::RECAP_SHOWN;

/// The generated file's content.
#[must_use]
pub fn render() -> String {
    let mut out = String::from(
        "// Generated by `just bindings` from apps/desktop/src-tauri (commands.rs, push.rs) and crates/tokenmtr-brand. Do not edit.\n\n",
    );
    out.push_str(
        "/** Product-name constants (crates/tokenmtr-brand). */\nexport const BRAND = {\n",
    );
    for (key, value) in [
        ("displayName", brand::DISPLAY_NAME),
        ("cliName", brand::CLI_NAME),
        ("bundleId", brand::BUNDLE_ID),
        ("configDirName", brand::CONFIG_DIR_NAME),
        ("configFileName", brand::CONFIG_FILE_NAME),
        ("logDirName", brand::LOG_DIR_NAME),
        ("envConfig", brand::ENV_CONFIG),
    ] {
        let _ = writeln!(out, "  {key}: \"{value}\",");
    }
    out.push_str("} as const;\n\n/** The product's display name. */\nexport const APP_NAME = BRAND.displayName;\n\n");
    out.push_str("/** Every Tauri command the shell registers. */\nexport const COMMANDS = [\n");
    for name in NAMES {
        let _ = writeln!(out, "  \"{name}\",");
    }
    out.push_str("] as const;\n\nexport type Command = (typeof COMMANDS)[number];\n\n");
    out.push_str("/** Events the shell emits to the webviews. */\nexport const EVENTS = {\n");
    for (key, name) in [
        ("storeChanged", STORE_CHANGED),
        ("alertFired", ALERT_FIRED),
        ("daemonState", DAEMON_STATE),
        ("navigate", NAVIGATE),
        ("recapShown", RECAP_SHOWN),
    ] {
        let _ = writeln!(out, "  {key}: \"{name}\",");
    }
    out.push_str("} as const;\n\n");
    out.push_str(
        "/** `kind` of a failed command's `{ kind, message }`. */\nexport const ERROR_KINDS = [\n",
    );
    for (_, name) in ErrorKind::ALL {
        let _ = writeln!(out, "  \"{name}\",");
    }
    out.push_str("] as const;\n");
    out
}

#[cfg(test)]
mod tests {
    use std::path::PathBuf;

    use tokenmtr_core::brand;

    use super::render;

    fn target() -> PathBuf {
        PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../src/shared/bindings.ts")
    }

    /// Rewrites the file with `UPDATE_BINDINGS=1` (`just bindings`); otherwise fails when stale.
    #[test]
    fn bindings_file_is_current() -> Result<(), Box<dyn std::error::Error>> {
        let wanted = render();
        if std::env::var_os("UPDATE_BINDINGS").is_some() {
            std::fs::write(target(), &wanted)?;
            return Ok(());
        }
        let current = std::fs::read_to_string(target()).unwrap_or_default();
        assert!(
            current == wanted,
            "apps/desktop/src/shared/bindings.ts is stale; run `just bindings`"
        );
        Ok(())
    }

    /// `tauri.conf.json` cannot read Rust constants, so this keeps its names on the brand crate.
    #[test]
    fn tauri_conf_names_match_the_brand() -> Result<(), Box<dyn std::error::Error>> {
        let path = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("tauri.conf.json");
        let conf: serde_json::Value = serde_json::from_str(&std::fs::read_to_string(path)?)?;
        for (key, wanted) in [
            ("productName", brand::DISPLAY_NAME),
            ("identifier", brand::BUNDLE_ID),
            ("mainBinaryName", brand::DESKTOP_BINARY_NAME),
        ] {
            assert_eq!(conf[key].as_str(), Some(wanted), "tauri.conf.json `{key}`");
        }
        Ok(())
    }

    /// The Linux packages take their name from `productName` (kebab-cased), so it must be the
    /// CLI name: the deb, the rpm and `/usr/share/doc/<name>` agree with `tokenmtr`.
    #[test]
    fn linux_packages_are_named_after_the_cli() -> Result<(), Box<dyn std::error::Error>> {
        let path = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("tauri.linux.conf.json");
        let conf: serde_json::Value = serde_json::from_str(&std::fs::read_to_string(path)?)?;
        assert_eq!(conf["productName"].as_str(), Some(brand::CLI_NAME));
        Ok(())
    }
}
